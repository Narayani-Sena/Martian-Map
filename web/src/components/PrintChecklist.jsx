import React from 'react'
import { UI_CHATTER, useStoreExcept } from '../store.js'
import { buildChecklist } from './checklist.js'
import { fmtDist, fmtDur, fmtUtc } from '../lib/format.js'

// Rendered only for window.print(): a two-column, black-on-white cuff checklist.
export default function PrintChecklist() {
  const state = useStoreExcept(UI_CHATTER)
  const cl = buildChecklist(state.plan, state)
  if (!cl) return null
  const t = cl.totals
  const box = { border: '1.5px solid #000', borderRadius: 6, padding: '6px 8px', marginBottom: 6, breakInside: 'avoid' }
  return (
    <div className="print-only" style={{ fontFamily: 'Inter, Arial, sans-serif', color: '#000', padding: 12, fontSize: 11 }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', borderBottom: '3px solid #000', paddingBottom: 6, marginBottom: 8 }}>
        <div>
          <div style={{ fontSize: 18, fontWeight: 800 }}>EVA-1 CUFF CHECKLIST</div>
          <div>{state.site.name} · {state.site.region}</div>
        </div>
        <div style={{ textAlign: 'right' }}>
          <div><b>Sol {t.mission_sol}</b> · start {fmtUtc(t.start_utc)}</div>
          <div>{fmtDist(t.dist_m)} · {fmtDur(t.total_s)} suited · {t.go ? 'GO' : 'NO-GO'}</div>
        </div>
      </div>
      <div style={{ ...box, background: '#eee' }}>
        <b>FLIGHT RULES</b>
        <ol style={{ margin: '4px 0 0', paddingLeft: 18 }}>{cl.rules.map((r, i) => <li key={i}>{r}</li>)}</ol>
      </div>
      <div style={{ columns: 2, columnGap: 12 }}>
        {cl.rows.map((r, i) => (
          <div key={i} style={box}>
            <div style={{ display: 'flex', justifyContent: 'space-between' }}><b>{r.title}</b><span style={{ fontFamily: 'monospace' }}>{r.t} · {r.ltst}</span></div>
            {r.lines.map((l, k) => <div key={k}>☐ {l}</div>)}
          </div>
        ))}
      </div>
      <div style={{ marginTop: 6, fontSize: 9 }}>Generated by Martian Map. Terrain: HiRISE DTM (USGS). Times in Local True Solar Time at the site.</div>
    </div>
  )
}
